history = {}
meta = {}

def register(raw_dict, month_list, brand):
    for name, vals in raw_dict.items():
        vals = [max(0, v) for v in vals]  # 반품 등 음수는 0 처리
        history[name] = dict(zip(month_list, vals))
        meta[name] = {"brand": brand, "unit": "개"}

